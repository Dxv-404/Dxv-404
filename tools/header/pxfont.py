W, H = 5, 7


def glyph(ch):
    rows = G.get(ch.upper(), G["?"]).split()
    return np.array([[int(c) for c in r] for r in rows], np.uint8)


def measure(text, scale=1, tracking=1):
    return (len(text) * (W + tracking) - tracking) * scale, H * scale


def stamp(canvas, text, x, y, colour, scale=1, tracking=1):
    """draw `text` into an HxWx4 RGBA numpy canvas at art-grid (x, y)."""
    cx = x
    for ch in text:
        g = glyph(ch)
        if scale > 1:
            g = np.kron(g, np.ones((scale, scale), np.uint8))
        gh, gw = g.shape
        y0, y1 = y, y + gh
        x0, x1 = cx, cx + gw
        if x1 > 0 and y1 > 0 and x0 < canvas.shape[1] and y0 < canvas.shape[0]:
            sx0, sy0 = max(0, -x0), max(0, -y0)
            X0, Y0 = max(0, x0), max(0, y0)
            X1, Y1 = min(canvas.shape[1], x1), min(canvas.shape[0], y1)
            sub = g[sy0:sy0 + (Y1 - Y0), sx0:sx0 + (X1 - X0)]
            m = sub > 0
            canvas[Y0:Y1, X0:X1][m] = list(colour) + [255]
        cx += (W + tracking) * scale
    return canvas
