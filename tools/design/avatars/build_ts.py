"""Turns the approved avatars (avatars.json, same folder) into the app's modules. Run after gen.py:

    python3 tools/design/avatars/build_ts.py

Writes
  packages/protocol/src/avatars.ts   the ids (small; the table servers and the app validate with it)
  apps/web/src/avatars/set.ts        names, kinds and the SVG of every avatar (the app loads it lazily)

The SVG is kept as drawn, with two clean-ups: the inner ids all start with "tpav-" (the app makes them unique
for every copy it puts on screen), and a hidden layer of the Noir femme that pointed at a gradient nobody
defines (url(#nv), opacity 0) is dropped.
"""
import ast, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
AV = json.load(open(os.path.join(HERE, 'avatars.json')))
THEMES = ['classic', 'noir', 'ivory', 'velvet', 'cyber', 'ink', 'pixel', 'train', 'edo']
# the board's own palette per theme (board.py T: bg, tx, mut, acc, ...; [8] the label): tile swatches and tabs
_tree = ast.parse(open(os.path.join(HERE, 'board.py')).read())
_T = next(ast.literal_eval(n.value) for n in _tree.body if isinstance(n, ast.Assign) and getattr(n.targets[0], 'id', '') == 'T')
LOOK = {k: {'label': _T[k][8], 'bg': _T[k][0], 'tx': _T[k][1], 'acc': _T[k][3]} for k in THEMES}
ID = re.compile(r'^[a-z]+(-[a-z0-9]+){1,4}$')

assert list(AV.keys()) == THEMES, f'themes out of order: {list(AV.keys())}'
ids, rows = [], []
for k in THEMES:
    assert len(AV[k]) == 8, f'{k}: {len(AV[k])} avatars'
    for a in AV[k]:
        aid = a['id']
        assert ID.match(aid) and aid.startswith(k + '-') and len(aid) <= 40, f'bad id {aid}'
        assert aid not in ids, f'duplicate id {aid}'
        svg = a['svg']
        svg = re.sub(r'<path [^>]*fill="url\(#nv\)"[^>]*/>', '', svg)  # the invisible layer with a missing gradient
        inner = set(re.findall(r'id="([^"]+)"', svg))
        refs = set(re.findall(r'(?:url\(#|href="#)([^")]+)', svg))
        assert all(i.startswith('tpav-') for i in inner), f'{aid}: ids {inner}'
        assert refs <= inner, f'{aid}: refers to {refs - inner}'
        assert svg.startswith('<svg ') and 'viewBox="0 0 64 64"' in svg and '<script' not in svg and not re.search(r'\son\w+=', svg)
        svg = svg.replace('<svg ', '<svg aria-hidden="true" focusable="false" ', 1)
        ids.append(aid)
        rows.append((aid, k, a['name'], a['kind'], svg))

js = lambda s: json.dumps(s, ensure_ascii=False)
HEAD = '// Generated by tools/design/avatars/build_ts.py from avatars.json (the approved board). Do not edit.\n'

proto = HEAD + f'''
/** The themes the avatars are drawn in (each avatar keeps its own style at every table). */
export const AVATAR_THEMES = {js(THEMES)} as const;
export type AvatarTheme = (typeof AVATAR_THEMES)[number];
/** Every avatar a player can pick, theme by theme (8 each). */
export const AVATAR_IDS = {js(ids)} as const;
export type AvatarId = (typeof AVATAR_IDS)[number];
/** The shape of an avatar id (newer apps may know ids this one does not: they are shown as initials). */
export const AVATAR_PATTERN = /^[a-z]+(-[a-z0-9]+){{1,4}}$/;
const KNOWN: ReadonlySet<string> = new Set(AVATAR_IDS);
/** One of the avatars this build knows. */
export const isAvatarId = (s: unknown): s is AvatarId => typeof s === 'string' && KNOWN.has(s);
/** The theme an avatar is drawn in. */
export const avatarTheme = (id: AvatarId): AvatarTheme => id.slice(0, id.indexOf('-')) as AvatarTheme;
/** accounts.avatar_url ("tp:train-night-owl") -> the avatar id, or null (initials, a photo url, anything unknown). */
export const avatarFromStored = (v: unknown): AvatarId | null => (typeof v === 'string' && v.startsWith('tp:') && isAvatarId(v.slice(3)) ? (v.slice(3) as AvatarId) : null);
'''

body = ',\n'.join(f'  {js(aid)}: {{ theme: {js(k)}, name: {js(n)}, kind: {js(kind)}, svg: {js(svg)} }}' for aid, k, n, kind, svg in rows)
web = HEAD + f'''// Loaded lazily (about 230 KB before compression): see ./index.ts.
import type {{ AvatarId, AvatarTheme }} from '@tp/protocol/avatars';

export interface AvatarArt {{ theme: AvatarTheme; name: string; kind: 'character' | 'emblem'; svg: string }}
export const AVATARS: Record<AvatarId, AvatarArt> = {{
{body},
}};
/** Each style's name and colours on the board: the swatch in the tabs, the tile behind each avatar. */
export const STYLE_LOOK: Record<AvatarTheme, {{ label: string; bg: string; tx: string; acc: string }}> = {js(LOOK)};
'''

for path, text in [('packages/protocol/src/avatars.ts', proto), ('apps/web/src/avatars/set.ts', web)]:
    p = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, 'w').write(text)
    print('wrote', path, len(text) // 1024, 'KB')
